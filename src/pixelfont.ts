const BLANK = Array<string>(GLYPH_HEIGHT).fill('.'.repeat(GLYPH_WIDTH));

/** Rows of one glyph; anything unknown is blank. */
export function glyph(char: string): string[] {
  return GLYPHS[char] ?? BLANK;
}
